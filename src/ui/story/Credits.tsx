/**
 * In-game credits for Story Mode: the music (six Musopen piano recordings from Wikimedia Commons, each
 * with its recording licence; docs/MUSIC_CREDITS.md has the full record), the synthesized sound
 * (docs/AUDIO_CREDITS.md) and the science sources the facts quote. Read from the same tables the game
 * plays and shows (src/audio/tracks.ts, src/story/science.ts), so the credits cannot drift from what is
 * actually used.
 */
import { CUE_TRACKS, type TrackDef } from '../../audio/tracks';
import { CLIMATE_FACTS } from '../../story/science';
import type { ClimateFact } from '../../story/types';

export const MUSOPEN_URL = 'https://musopen.org/';

/** The one-line credit under the chapter list. */
export const MUSIC_CREDIT_LINE =
  'Music: solo-piano recordings from Musopen, via Wikimedia Commons (public domain and CC0). ' +
  'Full credits under Science Behind the Story.';

/** Everything that is not one of the recordings (docs/AUDIO_CREDITS.md has the full table). */
export const SOUND_CREDIT_LINE =
  "Sound effects, ambience, bells and the archive's piano motif are synthesized in the browser; the motif is an " +
  'original composition for this game (2026). None of them uses a sample or a recording.';

/** Items once per key, in first-seen order. */
const uniqueBy = <T,>(items: readonly T[], key: (t: T) => string): T[] => [...new Map(items.map((t) => [key(t), t])).values()];

/** Each recording once, in cue order. */
export const creditedTracks = (): TrackDef[] => uniqueBy(Object.values(CUE_TRACKS), (t) => t.file);

/** Each cited source page once, in the order the facts cite them. */
export const creditedSources = (facts: readonly ClimateFact[] = CLIMATE_FACTS): ClimateFact['source'][] =>
  uniqueBy(
    facts.map((f) => f.source),
    (s) => s.url,
  );

export function StoryCredits() {
  const tracks = creditedTracks();
  const sources = creditedSources();
  const orgs = [...new Set(sources.map((s) => s.org))];
  return (
    <section className="story-credits" aria-labelledby="credits-title">
      <h2 className="story-section-title" id="credits-title">
        Credits
      </h2>
      <h3 className="story-credits__h">Music</h3>
      <p className="story-credits__note">
        Six solo-piano recordings from{' '}
        <a href={MUSOPEN_URL} target="_blank" rel="noreferrer noopener">
          Musopen
        </a>
        , taken from Wikimedia Commons, where each file page releases the recording itself into the public domain or
        under CC0. Played in Story Mode; Arcade Mode plays the first two.
      </p>
      <ul className="story-credits__list">
        {tracks.map((t) => (
          <li key={t.file}>
            <span className="story-credits__work">{t.title}</span> — {t.composer}. {t.performer}. {t.licence} ·{' '}
            <a href={t.source} target="_blank" rel="noreferrer noopener">
              Wikimedia Commons
            </a>
          </li>
        ))}
      </ul>
      <h3 className="story-credits__h">Sound</h3>
      <p className="story-credits__note">{SOUND_CREDIT_LINE}</p>
      <h3 className="story-credits__h">Science</h3>
      <p className="story-credits__note">
        The statements above are quoted from public pages of {orgs.join(', ')}; each is linked with the date it was
        checked.
      </p>
      <ul className="story-credits__list">
        {sources.map((s) => (
          <li key={s.url}>
            {s.org} ·{' '}
            <a href={s.url} target="_blank" rel="noreferrer noopener">
              {s.title}
            </a>
          </li>
        ))}
      </ul>
      <h3 className="story-credits__h">Story and game</h3>
      <p className="story-credits__note">
        The Last Thaw's towns, people and records are invented. Reflections marked as written by the Archivist are
        generated by two language-model agents and checked against your run before they are shown. Built with three.js,
        React Three Fiber, Rapier and React; code written with AI assistance (Claude Code).
      </p>
    </section>
  );
}
