import { appendFileSync, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import type { AgentName, AgentTraceStep, UsageRecord } from '../story/types';
import { providerOf, type ProviderId } from './config';

/**
 * Evidence of what the agents did: one UsageRecord line per agent invocation in
 * logs/agent-usage.jsonl (token counts copied from the API's usage objects; a request that returned
 * none, e.g. one that timed out, is counted in unmeteredRequests, not estimated) and a full trace per
 * narrative in logs/traces/<runId>.json. Plus the numbers GET /api/story/usage reports, and a cost
 * estimate built only from MEASURED averages, with its assumptions written into its own output.
 */

/** Records the steps of one narrative run, in order, with ms since the run started. */
export class Trace {
  readonly steps: AgentTraceStep[] = [];
  private readonly started: number;

  constructor(
    readonly runId: string,
    private readonly now: () => number = Date.now,
  ) {
    this.started = now();
  }

  step(agent: AgentName, kind: AgentTraceStep['kind'], summary: string, data?: unknown): void {
    this.steps.push({ agent, kind, at: this.now() - this.started, summary, ...(data === undefined ? {} : { data }) });
  }
}

/** Where usage and traces go (files in production, memory in tests). */
export interface UsageLogger {
  appendUsage(records: readonly UsageRecord[]): void;
  writeTrace(runId: string, trace: unknown): void;
  readUsage(): UsageRecord[];
}

/** runIds are generated by the server; this guard keeps any other string out of a file path. */
const SAFE_RUN_ID = /^[A-Za-z0-9_-]{1,80}$/;
/** Read at most this much of the usage log for summaries (the newest part). */
const MAX_USAGE_READ_BYTES = 4 * 1024 * 1024;

export function fileLogger(logsDir: string): UsageLogger {
  const usageFile = path.join(logsDir, 'agent-usage.jsonl');
  const tracesDir = path.join(logsDir, 'traces');
  return {
    appendUsage(records) {
      if (records.length === 0) return;
      mkdirSync(logsDir, { recursive: true });
      appendFileSync(usageFile, records.map((r) => JSON.stringify(r)).join('\n') + '\n', 'utf8');
    },
    writeTrace(runId, trace) {
      if (!SAFE_RUN_ID.test(runId)) throw new Error('unsafe run id');
      mkdirSync(tracesDir, { recursive: true });
      writeFileSync(path.join(tracesDir, `${runId}.json`), JSON.stringify(trace, null, 2), 'utf8');
    },
    readUsage() {
      if (!existsSync(usageFile)) return [];
      const size = statSync(usageFile).size;
      let text = readFileSync(usageFile, 'utf8');
      if (size > MAX_USAGE_READ_BYTES) text = text.slice(text.length - MAX_USAGE_READ_BYTES).replace(/^[^\n]*\n/, '');
      return parseUsageLines(text);
    },
  };
}

export function memoryLogger(): UsageLogger & { readonly usage: UsageRecord[]; readonly traces: Map<string, unknown> } {
  const usage: UsageRecord[] = [];
  const traces = new Map<string, unknown>();
  return {
    usage,
    traces,
    appendUsage: (r) => void usage.push(...r),
    writeTrace: (id, t) => void traces.set(id, JSON.parse(JSON.stringify(t))),
    readUsage: () => [...usage],
  };
}

const isNum = (v: unknown): v is number => typeof v === 'number' && Number.isFinite(v);

/** Parses JSONL usage records, skipping any line that is not a well-formed record. */
export function parseUsageLines(text: string): UsageRecord[] {
  const out: UsageRecord[] = [];
  for (const line of text.split('\n')) {
    if (!line.trim()) continue;
    try {
      const r = JSON.parse(line) as UsageRecord;
      if (typeof r.runId === 'string' && (r.agent === 'archivist' || r.agent === 'historian') && isNum(r.inputTokens) && isNum(r.outputTokens)) {
        out.push(r);
      }
    } catch {
      // a torn last line (process killed mid-write) is skipped
    }
  }
  return out;
}

/** Tokens (input + output) logged on a UTC day, to seed the daily budget after a restart. */
export const tokensOnDay = (records: readonly UsageRecord[], day: string): number =>
  records.filter((r) => r.ts.startsWith(day)).reduce((a, r) => a + r.inputTokens + r.outputTokens, 0);

/** Which key paid for a record (records from before the provider was logged are all on the course key). */
export const providerOfRecord = (r: UsageRecord): ProviderId | undefined => r.provider ?? providerOf(r.model);

/** USD logged on a UTC day for one provider, to seed the own-key daily limit after a restart. */
export const usdOnDay = (records: readonly UsageRecord[], day: string, provider: ProviderId): number =>
  records
    .filter((r) => r.ts.startsWith(day) && providerOfRecord(r) === provider)
    .reduce((a, r) => a + (isNum(r.costUsd) ? Math.max(0, r.costUsd) : 0), 0);

// -------------------------------------------------------------------------------------------------
// Summary and cost estimate (GET /api/story/usage)
// -------------------------------------------------------------------------------------------------

export interface UsageTotals {
  readonly invocations: number;
  readonly requests: number;
  readonly toolCalls: number;
  readonly inputTokens: number;
  readonly cachedInputTokens: number;
  /** 0 for records logged before cache writes were recorded. */
  readonly cacheWriteTokens: number;
  readonly outputTokens: number;
  readonly reasoningTokens: number;
  /** Requests sent whose usage never came back (timed out, cancelled, unreadable): the token counts are a lower bound. */
  readonly unmeteredRequests: number;
  /** Sum over records with a known price; null when none has one. */
  readonly costUsd: number | null;
  /** Records whose model had no verified price (excluded from costUsd). */
  readonly unpricedRecords: number;
  readonly failed: number;
}

function totals(records: readonly UsageRecord[]): UsageTotals {
  let cost = 0;
  let priced = 0;
  const t = {
    invocations: records.length,
    requests: 0,
    toolCalls: 0,
    inputTokens: 0,
    cachedInputTokens: 0,
    cacheWriteTokens: 0,
    outputTokens: 0,
    reasoningTokens: 0,
    unmeteredRequests: 0,
    failed: 0,
  };
  for (const r of records) {
    t.requests += r.requests;
    t.toolCalls += r.toolCalls;
    t.inputTokens += r.inputTokens;
    t.cachedInputTokens += r.cachedInputTokens;
    t.cacheWriteTokens += r.cacheWriteTokens ?? 0;
    t.outputTokens += r.outputTokens;
    t.reasoningTokens += r.reasoningTokens ?? 0;
    t.unmeteredRequests += r.unmeteredRequests ?? 0;
    if (!r.ok) t.failed++;
    if (r.costUsd !== null && isNum(r.costUsd)) {
      cost += r.costUsd;
      priced++;
    }
  }
  return { ...t, costUsd: priced > 0 ? Math.round(cost * 1e8) / 1e8 : null, unpricedRecords: records.length - priced };
}

export interface RunSummary {
  readonly runId: string;
  readonly ts: string;
  readonly model: string;
  readonly agents: UsageTotals;
  readonly ok: boolean;
}

export interface CostAssumptions {
  /** Narratives (reflection or epilogue requests that reached the model) per user per month. */
  readonly narrativesPerUserPerMonth: number;
  readonly note: string;
}

/**
 * Default assumption: one full playthrough per user per month asks for 5 narratives (reflections after
 * chapters 1, 4, 6 and 9 with the default 'selected' setting, plus the epilogue).
 */
export const DEFAULT_ASSUMPTIONS: CostAssumptions = {
  narrativesPerUserPerMonth: 5,
  note:
    'One playthrough per user per month with the default AI setting: reflections after chapters 1, 4, 6 and 9 plus the epilogue = 5 narratives. ' +
    'Replays, the "all chapters" setting and failed runs that fall back early change this linearly.',
};

export interface CostEstimate {
  readonly basedOnRuns: number;
  readonly model: string | null;
  readonly measured: {
    readonly avgCostPerNarrativeUsd: number | null;
    readonly avgInputTokensPerNarrative: number;
    readonly avgCachedInputTokensPerNarrative: number;
    readonly avgOutputTokensPerNarrative: number;
    readonly avgRequestsPerNarrative: number;
  };
  readonly perUserPerMonthUsd: number | null;
  readonly at100UsersPerMonthUsd: number | null;
  readonly at10000UsersPerMonthUsd: number | null;
  readonly assumptions: readonly string[];
}

/** One model's share of the log: which key paid, its totals and its own cost estimate. */
export interface ModelUsage {
  readonly model: string;
  readonly provider: ProviderId | null;
  readonly totals: UsageTotals;
  readonly estimate: CostEstimate;
}

export interface UsageSummary {
  readonly totals: UsageTotals;
  readonly byAgent: Readonly<Record<AgentName, UsageTotals>>;
  /** Per model, in order of first appearance (an array: a model name is never used as a key). */
  readonly byModel: readonly ModelUsage[];
  /** Newest first, at most 50. */
  readonly runs: readonly RunSummary[];
  readonly estimate: CostEstimate;
}

const round = (v: number, digits: number): number => Math.round(v * 10 ** digits) / 10 ** digits;

/** Where the records came from, as the estimate's assumptions name it. */
export const USAGE_LOG_SOURCE = 'logs/agent-usage.jsonl';

export function estimateCosts(
  records: readonly UsageRecord[],
  a: CostAssumptions = DEFAULT_ASSUMPTIONS,
  source: string = USAGE_LOG_SOURCE,
): CostEstimate {
  const byRun = new Map<string, UsageRecord[]>();
  for (const r of records) byRun.set(r.runId, [...(byRun.get(r.runId) ?? []), r]);
  const runs = [...byRun.values()].map(totals);
  const n = runs.length;
  const unmetered = runs.reduce((s, t) => s + t.unmeteredRequests, 0);
  const legacy = records.filter((r) => r.unmeteredRequests === undefined).length;
  const avg = (f: (t: UsageTotals) => number): number => (n ? round(runs.reduce((s, t) => s + f(t), 0) / n, 1) : 0);
  const pricedRuns = runs.filter((t) => t.costUsd !== null && t.unpricedRecords === 0);
  const avgCost = pricedRuns.length ? pricedRuns.reduce((s, t) => s + (t.costUsd ?? 0), 0) / pricedRuns.length : null;
  const perUser = avgCost === null ? null : avgCost * a.narrativesPerUserPerMonth;
  const models = [...new Set(records.map((r) => r.model))];
  return {
    basedOnRuns: n,
    model: models.length === 1 ? models[0] : null,
    measured: {
      avgCostPerNarrativeUsd: avgCost === null ? null : round(avgCost, 6),
      avgInputTokensPerNarrative: avg((t) => t.inputTokens),
      avgCachedInputTokensPerNarrative: avg((t) => t.cachedInputTokens),
      avgOutputTokensPerNarrative: avg((t) => t.outputTokens),
      avgRequestsPerNarrative: avg((t) => t.requests),
    },
    perUserPerMonthUsd: perUser === null ? null : round(perUser, 6),
    at100UsersPerMonthUsd: perUser === null ? null : round(perUser * 100, 4),
    at10000UsersPerMonthUsd: perUser === null ? null : round(perUser * 10_000, 2),
    assumptions: [
      `Averages are measured from ${n} logged narrative run(s) in ${source} (token counts from the API's usage objects; nothing estimated).`,
      unmetered > 0
        ? `${unmetered} request(s) were sent but returned no usage (timed out, cancelled or unreadable); the provider may have billed them, so these figures are a lower bound.`
        : legacy > 0
          ? `${legacy} record(s) predate the count of requests without usage: a timed-out request in them is not counted, so treat these figures as a lower bound.`
          : 'Every request counted here returned its usage.',
      ...(models.length > 1
        ? [`Runs on ${models.length} models (${models.join(', ')}) are pooled here; byModel gives each model's own estimate.`]
        : []),
      a.note,
      `Narratives per user per month: ${a.narrativesPerUserPerMonth}.`,
      'Prices: the per-model table in src/server/pricing.ts (the OpenAI pricing page; gpt-6-luna via Lecture 11). Runs on a model without a verified price are excluded from the cost averages.',
      'Linear scaling: no volume discounts, no change in cache hit rate with more users, no Portkey fees.',
      n < 5 ? 'Few runs measured: treat these figures as indicative only.' : 'Re-run after more play to tighten the averages.',
    ],
  };
}

export function summarizeUsage(records: readonly UsageRecord[], a: CostAssumptions = DEFAULT_ASSUMPTIONS): UsageSummary {
  const byRun = new Map<string, UsageRecord[]>();
  for (const r of records) byRun.set(r.runId, [...(byRun.get(r.runId) ?? []), r]);
  const runs: RunSummary[] = [...byRun.entries()]
    .map(([runId, rs]) => ({ runId, ts: rs[0].ts, model: rs[0].model, agents: totals(rs), ok: rs.every((r) => r.ok) }))
    .sort((x, y) => (x.ts < y.ts ? 1 : -1))
    .slice(0, 50);
  const models = [...new Set(records.map((r) => r.model))];
  return {
    totals: totals(records),
    byAgent: {
      archivist: totals(records.filter((r) => r.agent === 'archivist')),
      historian: totals(records.filter((r) => r.agent === 'historian')),
    },
    byModel: models.map((model) => {
      const rs = records.filter((r) => r.model === model);
      return { model, provider: providerOfRecord(rs[0]) ?? null, totals: totals(rs), estimate: estimateCosts(rs, a) };
    }),
    runs,
    estimate: estimateCosts(records, a),
  };
}
